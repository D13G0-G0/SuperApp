-- Esquema inicial: identidad (usuarios y roles), catálogo y entregas (logistics).

CREATE TABLE users (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name             VARCHAR(255) NOT NULL,
    email                 VARCHAR(255) NOT NULL,
    shipping_address_line VARCHAR(255),
    shipping_city         VARCHAR(255),
    shipping_state        VARCHAR(255),
    shipping_postal_code  VARCHAR(255),
    shipping_country      VARCHAR(255),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE user_roles (
    user_id BIGINT      NOT NULL,
    role    VARCHAR(20) NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_user_roles_role CHECK (role IN ('CUSTOMER', 'SELLER', 'DRIVER', 'ADMIN'))
);

CREATE TABLE listings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(255)   NOT NULL,
    description VARCHAR(1000)  NOT NULL,
    price       NUMERIC(12, 2) NOT NULL,
    category    VARCHAR(255)   NOT NULL,
    image_url   VARCHAR(500)   NOT NULL,
    status      VARCHAR(20)    NOT NULL DEFAULT 'PUBLISHED',
    seller_id   BIGINT         NOT NULL,
    created_at  TIMESTAMP(6)   NOT NULL,
    CONSTRAINT fk_listings_seller FOREIGN KEY (seller_id) REFERENCES users (id),
    CONSTRAINT ck_listings_price CHECK (price > 0),
    CONSTRAINT ck_listings_status CHECK (status IN ('PUBLISHED', 'SOLD', 'SUSPENDED'))
);

CREATE INDEX ix_listings_seller ON listings (seller_id);
CREATE INDEX ix_listings_status ON listings (status);

CREATE TABLE delivery_orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id       BIGINT,
    title            VARCHAR(150)   NOT NULL,
    description      VARCHAR(1000),
    pickup_address   VARCHAR(500)   NOT NULL,
    customer_id      BIGINT         NOT NULL,
    driver_id        BIGINT,
    status           VARCHAR(20)    NOT NULL DEFAULT 'PENDING',
    delivery_address VARCHAR(500)   NOT NULL,
    total            NUMERIC(12, 2) NOT NULL,
    delivery_fee     NUMERIC(12, 2) NOT NULL,
    created_at       TIMESTAMP(6)   NOT NULL,
    CONSTRAINT fk_delivery_orders_listing FOREIGN KEY (listing_id) REFERENCES listings (id),
    CONSTRAINT fk_delivery_orders_customer FOREIGN KEY (customer_id) REFERENCES users (id),
    CONSTRAINT fk_delivery_orders_driver FOREIGN KEY (driver_id) REFERENCES users (id),
    CONSTRAINT ck_delivery_orders_total CHECK (total >= 0),
    CONSTRAINT ck_delivery_orders_fee CHECK (delivery_fee >= 0),
    CONSTRAINT ck_delivery_orders_status
        CHECK (status IN ('PENDING', 'ACCEPTED', 'PICKED_UP', 'DELIVERED', 'CANCELLED'))
);

CREATE INDEX ix_delivery_orders_customer ON delivery_orders (customer_id);
CREATE INDEX ix_delivery_orders_driver ON delivery_orders (driver_id);
CREATE INDEX ix_delivery_orders_status ON delivery_orders (status);
