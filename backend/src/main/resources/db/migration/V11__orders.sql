-- Carrito y pedidos (FR-05, FR-06). Migración de la Persona B (V10..V19).

-- Carrito: lo que cada usuario piensa comprar. Una publicación aparece una sola vez por usuario.
CREATE TABLE cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    listing_id BIGINT       NOT NULL,
    added_at   TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_cart_items_user_listing UNIQUE (user_id, listing_id),
    CONSTRAINT fk_cart_items_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_items_listing FOREIGN KEY (listing_id) REFERENCES listings (id) ON DELETE CASCADE
);

-- Un pedido por vendedor en cada compra. El estado solo cambia por transiciones permitidas.
CREATE TABLE orders (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id   BIGINT         NOT NULL,
    seller_id  BIGINT         NOT NULL,
    total      NUMERIC(14, 2) NOT NULL,
    status     VARCHAR(20)    NOT NULL,
    created_at TIMESTAMP(6)   NOT NULL,
    updated_at TIMESTAMP(6)   NOT NULL,
    CONSTRAINT fk_orders_buyer FOREIGN KEY (buyer_id) REFERENCES users (id),
    CONSTRAINT fk_orders_seller FOREIGN KEY (seller_id) REFERENCES users (id),
    CONSTRAINT ck_orders_total CHECK (total > 0),
    CONSTRAINT ck_orders_status CHECK (status IN ('PAID', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT ck_orders_not_self CHECK (buyer_id <> seller_id)
);

CREATE INDEX ix_orders_buyer ON orders (buyer_id, created_at);
CREATE INDEX ix_orders_seller ON orders (seller_id, created_at);

-- Productos de cada pedido. Se copian título y precio: si el vendedor edita la publicación
-- después, el pedido conserva lo que se pagó.
CREATE TABLE order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL,
    listing_id BIGINT         NOT NULL,
    title      VARCHAR(255)   NOT NULL,
    price      NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_order_items_listing FOREIGN KEY (listing_id) REFERENCES listings (id),
    CONSTRAINT ck_order_items_price CHECK (price > 0)
);

CREATE INDEX ix_order_items_order ON order_items (order_id);
-- Una publicación solo puede estar en un pedido activo a la vez se garantiza con el bloqueo de fila
-- y el estado SOLD; este índice acelera "¿esta publicación se usa?" (borrado lógico de catálogo).
CREATE INDEX ix_order_items_listing ON order_items (listing_id);
