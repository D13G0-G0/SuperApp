-- Billetera (FR-07): una cuenta por usuario y movimientos inmutables.
-- Las migraciones de la Persona B van de V10 a V19.

CREATE TABLE wallet_accounts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT         NOT NULL,
    balance    NUMERIC(14, 2) NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6)   NOT NULL,
    CONSTRAINT uk_wallet_accounts_user UNIQUE (user_id),
    CONSTRAINT fk_wallet_accounts_user FOREIGN KEY (user_id) REFERENCES users (id),
    -- El saldo nunca puede quedar negativo, ni siquiera por un error del código.
    CONSTRAINT ck_wallet_accounts_balance CHECK (balance >= 0)
);

-- Cada recarga, pago, ingreso o reembolso queda registrado aquí y NUNCA se edita ni se borra.
-- balance_after guarda el saldo que quedó después del movimiento (sirve para auditar).
CREATE TABLE wallet_movements (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id     BIGINT         NOT NULL,
    type          VARCHAR(20)    NOT NULL,
    amount        NUMERIC(14, 2) NOT NULL,
    balance_after NUMERIC(14, 2) NOT NULL,
    description   VARCHAR(255)   NOT NULL,
    reference     VARCHAR(100),
    created_at    TIMESTAMP(6)   NOT NULL,
    CONSTRAINT fk_wallet_movements_wallet FOREIGN KEY (wallet_id) REFERENCES wallet_accounts (id),
    CONSTRAINT ck_wallet_movements_type CHECK (type IN ('TOP_UP', 'PAYMENT', 'INCOME', 'REFUND')),
    CONSTRAINT ck_wallet_movements_amount CHECK (amount > 0),
    CONSTRAINT ck_wallet_movements_balance CHECK (balance_after >= 0)
);

CREATE INDEX ix_wallet_movements_wallet ON wallet_movements (wallet_id, created_at);

-- Cada usuario que ya existe (cuentas semilla) arranca con su billetera en 0.
INSERT INTO wallet_accounts (user_id, balance, created_at)
SELECT id, 0, CURRENT_TIMESTAMP FROM users;
