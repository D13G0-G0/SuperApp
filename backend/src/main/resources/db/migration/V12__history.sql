-- Historial unificado (FR-08): lo que hizo cada usuario en la app, de cualquier módulo.
-- Cada módulo lo escribe con IHistory dentro de su propia transacción: si la operación se deshace,
-- el registro también. Las filas no se editan ni se borran (solo si se borra el usuario).

CREATE TABLE history_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT        NOT NULL,
    type       VARCHAR(20)   NOT NULL,
    title      VARCHAR(255)  NOT NULL,
    detail     VARCHAR(500),
    amount     NUMERIC(14, 2),
    reference  VARCHAR(100),
    created_at TIMESTAMP     NOT NULL,
    CONSTRAINT fk_history_events_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_history_events_type CHECK (type IN ('PURCHASE', 'SALE', 'WALLET', 'DELIVERY'))
);

CREATE INDEX idx_history_events_user_date ON history_events (user_id, created_at);
